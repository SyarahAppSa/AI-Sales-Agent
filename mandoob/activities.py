def normalize_selection(keys: list[str]) -> list[str]:
    """يقبل مفاتيح أنشطة أو قطاعات كاملة (sector:education) أو القديمة، ويعيد مفاتيح أنشطة فريدة بترتيب الدليل."""
    chosen: set[str] = set()
    for k in keys or []:
        if k == "__all__":
            chosen |= set(ACTIVITIES)
        elif k.startswith("sector:") and k[7:] in SECTORS:
            chosen |= set(SECTORS[k[7:]]["activities"])
        elif k.startswith("group:"):
            chosen |= set(next((g[2] for g in SEARCH_GROUPS if g[0] == k[6:]), []))
        elif k in ACTIVITIES:
            chosen.add(k)
        elif k in LEGACY:
            chosen |= set(LEGACY[k])
    return [k for k in ACTIVITIES if k in chosen]


def by_sector(keys: list[str]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for k in keys:
        out.setdefault(ACTIVITIES[k]["sector"], []).append(k)
    return out


def sector_queries(keys: list[str]) -> list[str]:
    """عبارات بحث القطاع: نشاط تلو نشاط بالتناوب، فتتنوع النتائج داخل القطاع منذ أول نداء."""
    lists = [ACTIVITIES[k]["q"] for k in keys]
    out, i = [], 0
    while any(i < len(x) for x in lists):
        for x in lists:
            if i < len(x):
                out.append(x[i])
        i += 1
    return list(dict.fromkeys(out))


def activity_hints(keys: list[str]) -> str:
    return "؛ ".join(f"{ACTIVITIES[k]['label']} ({ACTIVITIES[k]['vehicle']})" for k in keys)
